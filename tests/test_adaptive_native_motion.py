"""Execute the actual JSX verifier against synthetic AE property readbacks."""
import json
import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path
from unittest.mock import Mock, patch

from tests.test_adaptive_native_frames import adapter
from video_contracts import write


@unittest.skipUnless(shutil.which('node'), 'JS verifier checks require Node')
class NativePositionReadbackTest(unittest.TestCase):
    def check_position(self, actual, *, space='screen', three_d=False):
        with tempfile.TemporaryDirectory() as directory:
            folder = Path(directory)
            node = {'node_id': 'synthetic-record', 'text': 'SYNTHETIC',
                    'font': 'SyntheticFont', 'origin_object_id': 'synthetic-origin',
                    'source_refs': [], 'space': space, 'in_point': 0,
                    'out_point': 1, 'tracks': {'position': [[0, [10, 20]]]}}
            request = {'project': str(folder/'synthetic.aep'),
                       'spec': {'spec_sha': 'synthetic', 'canvas': {'duration': 1},
                                'camera': {'position': []}, 'nodes': [node]}}
            write(folder/'native-identity.json', {'comp_id': 1})
            native = {'project': request['project'], 'width': 3840, 'height': 2160,
                      'fps': 24, 'duration': 1,
                      'comment': json.dumps({'spec_sha': 'synthetic'}),
                      'objects': [dict(name=node['node_id'], text=node['text'],
                                      font=node['font'], comment=json.dumps({
                                          'origin_object_id': node['origin_object_id'],
                                          'source_refs': []}))]}
            client = Mock()

            def execute(name, arguments, **kwargs):
                code = arguments['code']
                if 'function verify(' not in code:
                    return {'content': json.dumps(native)}
                # Run precisely the verifier generated by adapter.audit, including
                # its screen/world and actual layer dimensionality conditions.
                setup = '''
const config = JSON.parse(process.argv[1]);
global.File = function(){this.open=()=>true;this.close=()=>{};
 this.read=()=>JSON.stringify(config.request);};
global.PropertyValueType={COLOR:1};
const empty={numKeys:0};
const record={threeDLayer:config.three_d,inPoint:0,outPoint:1,
 transform:{position:{numKeys:1,propertyValueType:2,
 keyTime:()=>0,keyValue:()=>config.actual}}};
global.AEMCP={compById:()=>({layer:(name)=>name==='COGNITIVE_ATTENTION'
 ? {transform:{position:empty}}:record})};
process.stdout.write(eval(config.code));
'''
                result = subprocess.run(['node', '-e', setup, json.dumps({
                    'request': request, 'actual': actual, 'three_d': three_d,
                    'code': code})], capture_output=True, text=True, check=True)
                return {'content': result.stdout}

            client.call.side_effect = execute
            with patch.object(adapter, 'current', return_value=request), \
                    patch.object(adapter, 'client', return_value=client):
                return adapter.audit(folder)

    def test_native_screen_position_zero_z_is_equivalent(self):
        self.assertEqual(self.check_position([10, 20, 0])['canvas'], '4K24')

    def test_wrong_screen_xy_remains_rejected(self):
        with self.assertRaisesRegex(ValueError, 'motion/timing'):
            self.check_position([11, 20, 0])

    def test_nonzero_screen_depth_remains_rejected(self):
        with self.assertRaisesRegex(ValueError, 'motion/timing'):
            self.check_position([10, 20, 5])

    def test_world_or_actual_3d_layer_cannot_use_screen_normalization(self):
        for parameters in ({'space': 'world', 'three_d': True},
                           {'space': 'screen', 'three_d': True}):
            with self.subTest(parameters=parameters):
                with self.assertRaisesRegex(ValueError, 'motion/timing'):
                    self.check_position([10, 20, 0], **parameters)


if __name__ == '__main__':
    unittest.main()
