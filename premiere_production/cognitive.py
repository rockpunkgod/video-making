"""Internal Cognitive Shot editing; frozen teaching in, native Premiere out.

This lane does not certify Student POV payoff or a public teaching release.
"""
from pathlib import Path
import math
import re

from video_contracts import read, write, sha
from creative_os.hero import file_sha
from ae_production.cognitive_execution import validate_inputs, TEMPLATE
from .music import verify_gain_keys


def caption_cues(path):
    rows = []
    def seconds(value):
        h, m, s = value.replace(',', '.').split(':')
        return int(h)*3600 + int(m)*60 + float(s)
    for block in re.split(r'\r?\n\s*\r?\n', Path(path).read_text(encoding='utf-8-sig').strip()):
        lines = block.splitlines()
        if len(lines) < 3 or '-->' not in lines[1]:
            raise ValueError('Frozen SRT caption syntax required')
        times = lines[1].split(' --> ')
        if len(times) != 2:
            raise ValueError('Invalid caption time range')
        rows.append(dict(start=seconds(times[0]), end=seconds(times[1]), text='\n'.join(lines[2:])))
    return rows


def preflight(request):
    production = read(request['production'])
    spec = validate_inputs(production)
    receipt = read(request['render_receipt'])
    if (receipt['spec_sha'] != spec['spec_sha'] or receipt['audio'] is not False
            or receipt['renderer'] != 'native_AE_TIFF' or receipt['frames'] != 480
            or receipt['template_sha'] != file_sha(TEMPLATE)
            or receipt['project_sha'] != file_sha(receipt['project'])
            or receipt['output_sha'] != file_sha(receipt['output'])):
        raise ValueError('Native AE handoff no longer matches its frozen inputs')
    audio = read(request['audio_plan'])
    if (audio['audio_plan_sha'] != sha({k:v for k,v in audio.items() if k != 'audio_plan_sha'})
            or audio['spec_sha'] != spec['spec_sha'] or audio['mix_owner'] != 'Premiere'
            or audio['beat_sync'] is not False or audio['duration'] != 20 or audio['fps'] != 24
            or audio['final_copy_sha'] != spec['copy_lock']['final_copy_sha']):
        raise ValueError('Frozen audio plan changed')
    voice = read(audio['voice_receipt'])
    excerpt = read(production['excerpt'])
    text = ' '.join(u['spoken_copy'] for u in excerpt['units'])
    expected_units = [dict(unit_id=u['unit_id'], spoken_copy=u['spoken_copy'],
                           claim_refs=u['source_claim_refs']) for u in excerpt['units']]
    if (sha(voice) != audio['voice_receipt_sha'] or voice['text'] != text
            or voice['text_sha'] != sha(text) or voice['units'] != expected_units
            or voice['spec_sha'] != spec['spec_sha']
            or voice['final_copy_sha'] != spec['copy_lock']['final_copy_sha']):
        raise ValueError('Voice copy or provenance changed')
    v = audio['voice']
    if (v['path'] != voice['path'] or v['sha256'] != voice['sha256']
            or file_sha(v['path']) != v['sha256'] or v['text_sha'] != voice['text_sha']
            or v['audio_track_index'] != 0
            or not all(math.isfinite(t) for t in (v['start'],v['end']))
            or not 0 <= v['start'] < v['end'] <= 20
            or abs(v['end']-v['start']-voice['duration']) > 1e-6):
        raise ValueError('Continuous voice timing or file changed')
    music = audio['music']
    if (file_sha(music['source_path']) != music['file_sha']
            or file_sha(music['clip_path']) != music['clip_sha']
            or music['audio_track_index'] != 1 or music['music_license_gate'] != 'HOLD'
            or music['public_use_allowed'] is not False):
        raise ValueError('Internal recording binding changed')
    keys = music['gain_keys']; times = [k['time_seconds'] for k in keys]
    if (not times or times != sorted(set(times)) or times[0] != 0
            or any(not math.isfinite(t) or not 0 <= t < 20 for t in times)
            or any(not math.isfinite(k['level_db']) or not -96 <= k['level_db'] <= 0 for k in keys)):
        raise ValueError('Music gain envelope invalid')
    if file_sha(request['captions']) != request['captions_sha']:
        raise ValueError('Final caption copy changed')
    cues = caption_cues(request['captions'])
    compact = lambda value: re.sub(r'\s', '', value)
    if compact(''.join(c['text'] for c in cues)) != compact(text):
        raise ValueError('Captions must preserve every frozen spoken claim and Stop')
    previous = 0
    for cue in cues:
        if not (previous <= cue['start'] < cue['end'] <= 20
                and v['start'] <= cue['start'] and cue['end'] <= v['end']+1/24):
            raise ValueError('Caption cue overlaps, exceeds or leaves the continuous take')
        previous = cue['end']
    # Optional Pedagogy binding is an independent teaching projection. A legacy
    # visual proof cannot claim it was generated by a new Student POV Copy layer.
    if request.get('pedagogy_plan'):
        from pedagogy import validate_plan
        plan = read(request['pedagogy_plan'])
        validate_plan(plan, read(production['bundle']), read(production['status']))
        if (plan['plan_sha'] != request['pedagogy_plan_sha'] or plan['availability']['status'] != 'READY'
                or plan['mode'] != 'worked_example'
                or plan['method_id'] != read(production['application'])['payload']['method']['method_id']):
            raise ValueError('Current bounded worked-example Plan required')
    return spec, receipt, audio, cues


def check_timeline(sequence, settings, sequence_id, receipt, audio, item_ids):
    if (sequence['id'] != sequence_id or sequence['pagination']['truncated']
            or abs(sequence['end']-20) > 1/48
            or settings['id'] != sequence_id
            or settings['frameSizeHorizontal'] != 1920 or settings['frameSizeVertical'] != 1080
            or settings['timebase'] != '10584000000'
            or settings['audioSampleRateHz'] != 48000 or settings['audioChannelCount'] != 2):
        raise ValueError('Native sequence profile or duration changed')
    expected = {'videoTracks': {0:[(receipt['output'],0,20,item_ids['motion'])]},
        'audioTracks': {0:[(audio['voice']['path'],audio['voice']['start'],audio['voice']['end'],item_ids['voice'])],
                        1:[(audio['music']['clip_path'],0,20,item_ids['music'])]}}
    observed = []
    for kind in ('videoTracks','audioTracks'):
        for index, track in enumerate(sequence[kind]):
            clips = track['clips']; targets = expected[kind].get(index, [])
            if len(clips) != len(targets):
                raise ValueError('Unexpected native clip or track')
            for clip,(path,start,end,source_id) in zip(clips,targets):
                if (clip['name'] != Path(path).name or abs(clip['start']-start)>1/48000
                        or abs(clip['duration']-(end-start))>1/48000):
                    raise ValueError('Native media shifted or truncated')
                observed.append((kind,clip,path,end-start,source_id))
    for kind, targets in expected.items():
        if len(sequence[kind]) <= max(targets):
            raise ValueError('Required native tracks missing')
    return observed


def export_internal(client, request):
    spec, receipt, audio, cues = preflight(request)
    identity = read(request['identity'])
    project = client.call('get_project_info')
    if Path(project['path']).resolve() != Path(request['project']).resolve():
        raise ValueError('Unexpected active Premiere project')
    sequence = client.call('get_active_sequence'); settings = client.call('get_sequence_settings')
    clips = check_timeline(sequence,settings,identity['sequence_id'],receipt,audio,identity['item_ids'])
    properties = []
    for kind, clip, path, length, source_id in clips:
        prop = client.call('get_clip_properties',{'node_id':clip['nodeId']})
        if (prop['inPoint'] != 0 or abs(prop['outPoint']-length)>1/48000
                or prop['isSpeedReversed']
                or abs((prop['outPoint']-prop['inPoint'])-prop['duration'])>1/48000):
            raise ValueError('Native source range or speed changed')
        properties.append(prop)
    # Project item media-path readback proves sources beyond an editable name.
    items = client.call('list_project_items')
    entries = items['items'] if isinstance(items,dict) else items
    for _,_,path,_,source_id in clips:
        entry = next((i for i in entries if i.get('nodeId')==source_id),None)
        if entry is None or Path(entry['mediaPath']).resolve() != Path(path).resolve():
            raise ValueError('Native source item identity changed')
    automation = read(request['music_automation'])
    actual = client.call('get_keyframes',automation['property_binding'])
    verify_gain_keys(actual,audio['music']['gain_keys'])
    output = Path(request['output']).resolve()
    if output.exists():
        raise ValueError('Preserve existing export; reconcile before another attempt')
    output.parent.mkdir(parents=True,exist_ok=True)
    client.call('save_project')
    capture = dict(spec_sha=spec['spec_sha'],audio_plan_sha=audio['audio_plan_sha'],
        input_bindings={
            'application_sha':spec['application_sha'],'parent_asset_id':spec['parent_asset_id'],
            'parent_semantic_sha':spec['parent_semantic_sha'],'source_sha':spec['source_sha'],
            'pedagogy_plan_sha':request.get('pedagogy_plan_sha'),
            'manifest_sha':spec['manifest_sha'],'native_ae_receipt_sha':sha(receipt)},
        copy_lock={'final_copy_sha':sha({'screen':spec['copy_lock']['final_copy_sha'],
            'voice':read(audio['voice_receipt'])['text_sha'],'captions':request['captions_sha']}),
            'polished_from_sha':None,'editorial_review_sha':None},
        project_sha=file_sha(request['project']),sequence=sequence,settings=settings,
        clip_properties=properties,music_readback=actual,captions_sha=request['captions_sha'],
        preset_sha=file_sha(request['preset']),teaching_release='HOLD',source_display_release='HOLD',
        editorial_release='HOLD',music_license_gate='HOLD',public_render_ready=False,
        human_taste_review='PENDING',student_pov_payoff_certification=False)
    write(output.with_suffix('.preflight.json'),capture)
    preflight(request)
    # No timeout retry: inspect the host/output before another mutation.
    result = client.call('export_sequence',dict(output_path=str(output),preset_path=request['preset'],
        range='entire',overwrite=False,timeout_minutes=15),timeout=960)
    preflight(request)
    result = dict(output=str(output),output_sha=file_sha(output),native_export=result,
        preflight_sha=sha(capture),spec_sha=spec['spec_sha'],public_render_ready=False,
        teaching_release='HOLD',source_display_release='HOLD',editorial_release='HOLD',
        music_license_gate='HOLD',human_taste_review='PENDING')
    write(output.with_suffix('.receipt.json'),result)
    return result


def main():
    import argparse
    from .mcp import PremiereMcpClient
    parser = argparse.ArgumentParser(description='Native Premiere internal Cognitive Shot export')
    parser.add_argument('request'); request = read(parser.parse_args().request)
    preflight(request)
    client = PremiereMcpClient(request['endpoint'],Path(request['token_file']).read_text().strip())
    client.initialize()
    export_internal(client,request)
    print('Native internal Cognitive Shot exported; human taste and public releases pending')


if __name__ == '__main__':
    main()
